test("unsaved validation errors block publication and navigation can be cancelled", async ({ page }) => {
  await page.goto("/classroom/login");
  await page.getByLabel("Teacher password").fill(process.env.CLASSROOM_E2E_PASSWORD!);
  await page.getByRole("button", { name: "Open Classroom" }).click();
  await page.goto("/classroom/studio");
  await page.getByRole("button", { name: "Create Exercise" }).click();
  await expect(page.getByRole("tab", { name: /Content/ })).toBeVisible();
  await page.getByRole("button", { name: "Publish exercise" }).click();
  await expect(page.getByRole("alert").filter({ hasText: "Required to publish" })).toContainText("Required to publish");
  await page.route("**/classroom/api/studio/exercises/*", async (route) => {
    if (route.request().method() === "PATCH") return route.fulfill({ status: 503, contentType: "application/json", body: '{"error":"Temporary test failure"}' });
    return route.continue();
  });
  await page.getByRole("tabpanel").getByLabel("Exercise title").fill("Unsaved lesson");
  await expect(page.getByText("Temporary test failure")).toBeVisible();
  const url = page.url();
  page.once("dialog", (dialog) => dialog.dismiss());
  await page.getByRole("link", { name: "Exercise library", exact: false }).click();
  await expect(page).toHaveURL(url);
  await expect(page.getByRole("tabpanel").getByLabel("Exercise title")).toHaveValue("Unsaved lesson");
});
